// Vendors the three.js addons this project needs as a single CLASSIC script.
//
// The project has no build step and loads three.js as a UMD global, but from
// r150 the addons ship ESM-only. This converts them mechanically rather than
// hand-editing: `import {...} from 'three'` becomes a destructure of the
// global, cross-addon imports resolve by concatenation order, and the exports
// are attached to THREE at the end.
//
//   node scripts/build-three-addons.mjs [revision]     # default r160
//
// Re-run after bumping src/vendor/three.min.js; the revision MUST match the
// core build or the addons will reference APIs that are not there.
import { writeFileSync } from "node:fs";

const rev = process.argv[2] || "r160";
const BASE = `https://raw.githubusercontent.com/mrdoob/three.js/${rev}/examples/jsm`;
// `provides` are re-exported to later files; `needs` are injected from earlier
// ones. Each file gets its own block scope -- they all destructure overlapping
// names out of THREE, so a shared scope collides immediately.
const FILES = [
  { path: "utils/BufferGeometryUtils.js", slot: "BGU",
    provides: ["toTrianglesDrawMode", "mergeGeometries", "mergeVertices"], needs: [] },
  { path: "loaders/GLTFLoader.js", slot: "GLTF",
    provides: ["GLTFLoader"], needs: [["BGU", ["toTrianglesDrawMode"]]] },
  { path: "utils/SkeletonUtils.js", slot: "SKEL",
    provides: ["clone", "retarget", "retargetClip"], needs: [] },
];

const strip = (src) =>
  src
    // `import { A, B } from 'three'` -> destructure the UMD global
    .replace(/import\s*\{([^}]*)\}\s*from\s*['"]three['"];?/g, (_, names) => `const {${names}} = THREE;`)
    // cross-addon imports are satisfied by concatenation order
    .replace(/import\s*\{[^}]*\}\s*from\s*['"]\.\.?\/[^'"]+['"];?/g, "")
    // drop the trailing `export { ... };` manifests
    .replace(/export\s*\{[^}]*\};?/g, "")
    // `export function` / `export class` / `export const` -> plain declarations
    .replace(/^export\s+(function|class|const|let)\s/gm, "$1 ");

const parts = [];
for (const f of FILES) {
  const res = await fetch(`${BASE}/${f.path}`);
  if (!res.ok) throw new Error(`${f.path}: HTTP ${res.status}`);
  const src = await res.text();
  const inject = f.needs
    .map(([slot, names]) => `  const { ${names.join(", ")} } = __${slot};`)
    .join("\n");
  parts.push(
    `\n// ---- three.js ${rev} / ${f.path} ----\n{\n${inject}\n${strip(src)}\n` +
      `  __${f.slot} = { ${f.provides.join(", ")} };\n}`
  );
  console.log(`${f.path}: ${src.length} bytes`);
}

const out = `"use strict";
// GENERATED by scripts/build-three-addons.mjs -- do not edit by hand.
// three.js ${rev} addons, converted from ESM to a classic script.
// Upstream: https://github.com/mrdoob/three.js (MIT)
(() => {
  const THREE = globalThis.THREE;
  if (!THREE) throw new Error("three.js must load before its addons");
  let ${FILES.map((f) => `__${f.slot}`).join(", ")};
${parts.join("\n")}

  THREE.GLTFLoader = __GLTF.GLTFLoader;
  THREE.SkeletonUtils = __SKEL;
  THREE.BufferGeometryUtils = __BGU;
})();
`;
writeFileSync(new URL("../src/vendor/three-addons.js", import.meta.url), out);
console.log(`\nwrote src/vendor/three-addons.js (${out.length} bytes)`);
